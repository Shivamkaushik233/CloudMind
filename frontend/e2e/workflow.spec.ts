import {test,expect} from "@playwright/test";

test("register, train, investigate, scale, export and sign out",async({page})=>{
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/");
  await page.getByRole("button",{name:"Register New Account"}).click();
  await page.getByPlaceholder("Jane Developer").fill("Release Tester");
  await page.getByPlaceholder("developer@example.com").fill(`release-${Date.now()}@example.com`);
  await page.getByPlaceholder("Choose a secure password").fill("Release-test-password-2026!");
  await page.getByRole("button",{name:"Create Account & Sign in"}).click();
  await page.getByRole("button",{name:"Operations",exact:true}).click();
  await page.getByRole("button",{name:"Create demo workspace"}).click();
  await expect(page.getByText("SIMULATED DATA",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Forecast",exact:true}).click();
  await expect(page.getByRole("heading",{name:"30-minute traffic forecast"})).toBeVisible();
  await page.getByLabel("Forecast algorithm",{exact:true}).selectOption("xgboost");
  await page.getByRole("button",{name:"Train selected model"}).click();
  await expect(page.getByText("Model trained and saved.",{exact:true})).toBeVisible({timeout:60000});
  await expect(page.getByRole("heading",{name:"30-minute traffic forecast"})).toBeVisible();
  await page.getByRole("button",{name:"Monitor",exact:true}).click();
  await page.getByRole("button",{name:"Inject simulated incident"}).click();
  await expect(page.getByText("A ten-minute synthetic incident is now active.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Investigation",exact:true}).click();
  await page.getByRole("button",{name:"Run investigation"}).click();
  await expect(page.getByRole("heading",{name:"Recommended next steps"})).toBeVisible();
  await page.getByRole("button",{name:"Autoscaler",exact:true}).click();
  await page.getByLabel("Execution mode",{exact:true}).selectOption("simulation");
  await page.getByRole("button",{name:"Save policy",exact:true}).click();
  await expect(page.getByText("Policy saved.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Generate scaling plan"}).click();
  await page.getByRole("button",{name:"Apply to simulation",exact:true}).click();
  await expect(page.getByText("Simulation capacity updated.",{exact:true})).toBeVisible();
  const download=page.waitForEvent("download");
  await page.getByRole("button",{name:"Export CSV"}).click();
  expect((await download).suggestedFilename()).toBe("cloudmind-metrics.csv");
  await page.getByRole("button",{name:"Sign out",exact:true}).click();
  await expect(page.getByPlaceholder("you@example.com")).toBeVisible();
  expect(errors).toEqual([]);
});
